export interface IconDefinitionIconProps {
  icon: IconDefinition;
  /** Passed directly to the SVG without adding or merging classes. */
  className?: string;
  /** SVG size in pixels for numbers, or a CSS length. Defaults to one text em. */
  size?: number | string;
  /** Overrides the canonical regular weight (bold for Apple, GitHub and GitLab). */
  weight?: IconWeight;
  /** Accessible label; icons without a title are decorative. */
  title?: string;
}

/** Minimal IconDefinition adapter for React callers of the legacy Fa wrapper. */
export function IconDefinitionIcon({
  icon,
  className,
  size = '1em',
  weight,
  title,
}: IconDefinitionIconProps) {
  const Icon = iconComponents[getPhosphorIconSymbol(icon)];
  const iconWeight = weight ?? getPhosphorIconWeight(icon);

  return (
    <Icon
      className={className}
      size={size}
      weight={iconWeight}
      // oxlint-disable-next-line jsx-a11y/prefer-tag-over-role -- Preserve the source inline SVG image role and currentColor paths.
      role="img"
      data-icon={icon.iconName}
      data-weight={iconWeight}
      aria-label={title}
      aria-hidden={title ? undefined : 'true'}
    />
  );
}
