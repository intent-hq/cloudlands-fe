export type PhosphorIconSymbol = (typeof iconSymbols)[keyof typeof iconSymbols];

export function getPhosphorIconSymbol(iconDefinition: IconDefinition): PhosphorIconSymbol {
  return Object.hasOwn(iconSymbols, iconDefinition.iconName)
    ? iconSymbols[iconDefinition.iconName as keyof typeof iconSymbols]
    : 'QuestionIcon';
}

/** UI actions follow Phosphor's regular default; existing brand silhouettes stay unchanged. */
export function getPhosphorIconWeight(iconDefinition: IconDefinition): 'bold' | 'regular' {
  return iconDefinition.iconName === 'apple' ||
    iconDefinition.iconName === 'github' ||
    iconDefinition.iconName === 'gitlab'
    ? 'bold'
    : 'regular';
}
