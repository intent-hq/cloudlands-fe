import { test, expect } from '@playwright/test';
import { observeErrors } from '../lib/browser.mjs';

test('element picker respects controlled state, disabled input and fresh mounts', async ({
  page,
}, info) => {
  const base = process.env.REACT_BASE_URL;
  if (!base) throw new Error('Set REACT_BASE_URL to the maintained React preview');
  const errors = await observeErrors(page);
  await page.setViewportSize({ width: 420, height: 700 });
  const url = `${base}/sandbox/browser-device-frame?example=interactive&fit=component&motion=reduced`;
  await page.goto(url);
  const host = page.getByTestId('browser-device-frame-demo');
  const picker = host.getByTestId('browser-select-element');
  const hide = host.getByRole('button', { name: 'Hide frame', exact: true });
  await hide.focus();
  await page.keyboard.press('Tab');
  await expect(picker).toBeFocused();
  await page.keyboard.press('Enter');
  await expect(picker).toHaveAttribute('aria-pressed', 'true');
  await expect(host).toHaveAttribute('data-picker-toggles', '1');
  await page.keyboard.press('Space');
  await expect(picker).toHaveAttribute('aria-pressed', 'false');
  await expect(host).toHaveAttribute('data-picker-toggles', '2');
  await picker.hover();
  await expect(page.getByRole('tooltip', { name: 'Select an element', exact: true })).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('tooltip')).toHaveCount(0);
  await expect(picker).toBeFocused();
  await page.keyboard.press('Enter');
  await expect(picker).toHaveAttribute('aria-pressed', 'true');
  await expect(host).toHaveAttribute('data-picker-toggles', '3');
  await page.evaluate(() => document.fonts.ready);
  const active = info.outputPath('element-picker-active.png');
  await host.screenshot({ path: active });
  await info.attach('element-picker-active', { path: active, contentType: 'image/png' });
  await hide.click();
  await expect(picker).toBeDisabled();
  await expect(picker).toHaveAttribute('aria-pressed', 'false');
  const box = await picker.boundingBox();
  expect(box).not.toBeNull();
  await page.mouse.click(box.x + box.width / 2, box.y + box.height / 2);
  await expect(host).toHaveAttribute('data-picker-toggles', '3');
  const show = host.getByRole('button', { name: 'Show frame', exact: true });
  await show.focus();
  await page.keyboard.press('Tab');
  await expect(picker).not.toBeFocused();
  await show.click();
  await page.keyboard.press('Tab');
  await expect(picker).toBeFocused();
  await page.keyboard.press('Space');
  await expect(host).toHaveAttribute('data-picker-toggles', '4');
  await page.goto(`${base}/sandbox/device-icons?example=interactive&fit=component`);
  await expect(page.getByTestId('device-icons-demo')).toBeVisible();
  await page.goto(`${url}&theme=dark`);
  await expect(host).toHaveAttribute('data-picker-toggles', '0');
  await hide.focus();
  await page.keyboard.press('Tab');
  await page.keyboard.press('Enter');
  await expect(picker).toHaveAttribute('aria-pressed', 'true');
  await expect(host).toHaveAttribute('data-picker-toggles', '1');
  await page.evaluate(() => document.fonts.ready);
  const dark = info.outputPath('element-picker-dark.png');
  await host.screenshot({ path: dark });
  await info.attach('element-picker-dark', { path: dark, contentType: 'image/png' });
  expect(errors).toEqual([]);
});
