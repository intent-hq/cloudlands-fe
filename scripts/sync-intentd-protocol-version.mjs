import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { githubAuthToken, parseVersionPin, releaseTag } from './fetch-sidecar-lib.mjs';

// Writes src/test/current-protocol-version.ts: the PROTOCOL_VERSION of the intentd
// release pinned in intentd.version, which test fixtures use as their default
// `client.hello` protocolVersion. Fake hellos that hard-coded "14.0" kept passing after
// the daemon moved to 15, hiding a version cap that broke script lists for users
// (intent-hq/intent#7206); following the pinned daemon makes every protocol bump
// re-run hello-dependent tests against the new version.
//
// The auto-pin-intentd workflow runs this after each pin edit. The offline
// `lint:intentd-protocol-pin` gate fails when the recorded source pin no longer
// matches intentd.version (a hand-edited pin), and names this script as the fix.
//
// Exit codes: 0 ok; 1 stale (--check) or a fetch failure, which may be transient;
// 2 usage; 3 protocol.rs no longer has the expected PROTOCOL_VERSION shape, which
// needs a code change here (auto-pin fails loudly on it instead of skipping).
export const EXIT_SOURCE_FORMAT = 3;

export class ProtocolSourceFormatError extends Error {}

export const PIN_FILE = 'intentd.version';
export const OUTPUT_FILE = 'src/test/current-protocol-version.ts';
export const PROTOCOL_SOURCE_PATH = 'crates/intent-transport/src/protocol.rs';
const SOURCE_PIN_PATTERN = /^\/\/ source-pin: (\S+)$/m;
const VERSION_CONSTANT_PATTERN = /^export const CURRENT_PROTOCOL_VERSION = '([^']+)';/m;
// The constant is a test default, not a gate; lint:protocol-version-parsing sees a quoted
// `major.minor` next to a protocol name and needs its reasoned same-line escape.
const PARSE_ESCAPE = '// protocol-version-parse-ok: generated test default, not a gate';
const RUST_CONSTANT_PATTERN =
  /pub const PROTOCOL_VERSION:\s*&(?:'static\s+)?str\s*=\s*"(\d+\.\d+)";/g;

/** Extract the single `pub const PROTOCOL_VERSION: &str = "X.Y";` from protocol.rs. */
export function parseRustProtocolVersion(source) {
  const matches = [...source.matchAll(RUST_CONSTANT_PATTERN)];
  if (matches.length !== 1) {
    throw new ProtocolSourceFormatError(
      `Expected exactly one \`pub const PROTOCOL_VERSION: &str = "X.Y";\` in ${PROTOCOL_SOURCE_PATH}, found ${matches.length}`,
    );
  }
  return matches[0][1];
}

export function renderVersionModule({ pin, version }) {
  return [
    '// GENERATED by scripts/sync-intentd-protocol-version.mjs — do not edit by hand.',
    `// PROTOCOL_VERSION from ${PROTOCOL_SOURCE_PATH} at the bundled sidecar tag (intentd.version).`,
    '// Default protocolVersion for fake daemon hellos in tests; regenerate after a pin change.',
    '// protocol-version-ok-file: the generated value is the pinned daemon version by design.',
    `// source-pin: ${pin}`,
    `export const CURRENT_PROTOCOL_VERSION = '${version}'; ${PARSE_ESCAPE}`,
    '',
  ].join('\n');
}

/** Read `{ pin, version }` back from a generated module, or null when it is malformed. */
export function parseVersionModule(content) {
  const pin = content.match(SOURCE_PIN_PATTERN)?.[1];
  const version = content.match(VERSION_CONSTANT_PATTERN)?.[1];
  return pin && version ? { pin, version } : null;
}

export async function fetchProtocolSource(
  pin,
  { repo = process.env.INTENTD_REPO?.trim() || 'intent-hq/intentd', fetchImpl = fetch } = {},
) {
  const url = `https://api.github.com/repos/${repo}/contents/${PROTOCOL_SOURCE_PATH}?ref=${releaseTag(pin)}`;
  const headers = {
    accept: 'application/vnd.github.raw',
    'user-agent': 'cloudlands-fe sync-intentd-protocol-version',
    'x-github-api-version': '2022-11-28',
  };
  const token = githubAuthToken();
  if (token) headers.authorization = `Bearer ${token}`;
  const response = await fetchImpl(url, { headers });
  if (!response.ok) throw new Error(`GET ${url} failed: HTTP ${response.status}`);
  return response.text();
}

export async function main(argv = process.argv.slice(2), root = process.cwd(), deps = {}) {
  const unknown = argv.filter((argument) => argument !== '--check');
  if (unknown.length) {
    console.error(
      `Unknown argument(s): ${unknown.join(' ')}\nUsage: node scripts/sync-intentd-protocol-version.mjs [--check]`,
    );
    return 2;
  }
  const check = argv.includes('--check');
  const outputPath = path.join(root, OUTPUT_FILE);
  try {
    const pin = parseVersionPin(fs.readFileSync(path.join(root, PIN_FILE), 'utf8'));
    const version = parseRustProtocolVersion(await fetchProtocolSource(pin, deps));
    const expected = renderVersionModule({ pin, version });
    if (check) {
      const actual = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : '';
      if (actual !== expected) {
        console.error(
          `${OUTPUT_FILE} is stale: intentd v${pin} has PROTOCOL_VERSION ${version}. Run node scripts/sync-intentd-protocol-version.mjs`,
        );
        return 1;
      }
      console.log(`${OUTPUT_FILE} matches intentd v${pin} (PROTOCOL_VERSION ${version}).`);
      return 0;
    }
    fs.mkdirSync(path.dirname(outputPath), { recursive: true });
    fs.writeFileSync(outputPath, expected);
    console.log(`Wrote ${OUTPUT_FILE}: intentd v${pin} PROTOCOL_VERSION ${version}.`);
    return 0;
  } catch (error) {
    console.error(
      `sync-intentd-protocol-version: ${error instanceof Error ? error.message : error}`,
    );
    return error instanceof ProtocolSourceFormatError ? EXIT_SOURCE_FORMAT : 1;
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  process.exit(await main());
}
